const ESCAPES: Record<string, string> = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
}

/** Escapes `& < > " '`. With `encodeNonAscii`, every non-ASCII code point becomes a numeric entity. */
export function encodeEntities(text: string, encodeNonAscii = false): string {
  let out = ''
  for (const ch of text) {
    const escaped = ESCAPES[ch]
    if (escaped) out += escaped
    else if (encodeNonAscii && ch.codePointAt(0)! > 127) out += `&#${ch.codePointAt(0)};`
    else out += ch
  }
  return out
}

